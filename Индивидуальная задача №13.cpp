#include <iostream>
using namespace std;

int main() {
    char a;
    cin >> a;

    switch (a) {
        case 'a': cout << 250; break;
        case 'b': cout << 40; break;
        case 'm': cout << 280; break;
        case 'p': cout << 900; break;
        case 't': cout << 350; break;
    }

    return 0;
}
